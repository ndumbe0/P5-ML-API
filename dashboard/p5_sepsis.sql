-- ============ ANALYTICAL VIEWS ============

-- Sepsis positivity by age group
CREATE OR ALTER VIEW dbo.v_sepsis_by_age_group AS
SELECT age_group,
       COUNT(*)                                       AS patients,
       SUM(CAST(sepsis_positive AS INT))              AS positives,
       ROUND(100.0 * SUM(CAST(sepsis_positive AS INT)) / COUNT(*), 1) AS positive_rate_pct,
       ROUND(AVG(glucose), 1)                         AS avg_glucose,
       ROUND(AVG(bmi), 1)                             AS avg_bmi
FROM dbo.p5_sepsis_patients
GROUP BY age_group;;
GO

-- Sepsis positivity by BMI category
CREATE OR ALTER VIEW dbo.v_sepsis_by_bmi AS
SELECT bmi_category,
       COUNT(*)                                       AS patients,
       SUM(CAST(sepsis_positive AS INT))              AS positives,
       ROUND(100.0 * SUM(CAST(sepsis_positive AS INT)) / COUNT(*), 1) AS positive_rate_pct,
       ROUND(AVG(glucose), 1)                         AS avg_glucose,
       ROUND(AVG(bmi), 1)                             AS avg_bmi
FROM dbo.p5_sepsis_patients
GROUP BY bmi_category;;
GO

-- Sepsis positivity by insurance
CREATE OR ALTER VIEW dbo.v_sepsis_by_insurance AS
SELECT has_insurance,
       COUNT(*)                                       AS patients,
       SUM(CAST(sepsis_positive AS INT))              AS positives,
       ROUND(100.0 * SUM(CAST(sepsis_positive AS INT)) / COUNT(*), 1) AS positive_rate_pct,
       ROUND(AVG(glucose), 1)                         AS avg_glucose,
       ROUND(AVG(bmi), 1)                             AS avg_bmi
FROM dbo.p5_sepsis_patients
GROUP BY has_insurance;;
GO

-- Average clinical profile per outcome
CREATE OR ALTER VIEW dbo.v_glucose_bmi_profile AS
SELECT sepsis,
       COUNT(*)                  AS patients,
       ROUND(AVG(age), 1)        AS avg_age,
       ROUND(AVG(glucose), 1)    AS avg_glucose,
       ROUND(AVG(bp), 1)         AS avg_bp,
       ROUND(AVG(insulin), 1)    AS avg_insulin,
       ROUND(AVG(bmi), 1)        AS avg_bmi,
       ROUND(AVG(diabetes_pedigree), 3) AS avg_pedigree
FROM dbo.p5_sepsis_patients
GROUP BY sepsis;;
GO

-- Positive cases for triage review
CREATE OR ALTER VIEW dbo.v_high_risk_patients AS
SELECT patient_id, age, glucose, bmi, has_insurance, age_group, bmi_category
FROM dbo.p5_sepsis_patients
WHERE sepsis_positive = 1
ORDER BY glucose DESC;;
